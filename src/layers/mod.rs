/// Generate continuous effects from all permanents with static abilities
/// on the battlefield. This is called to refresh the effects list when
/// the battlefield changes.
pub fn generate_static_effects(
    battlefield: &[ObjectId],
    objects: &std::collections::HashMap<ObjectId, crate::card::CardInstance>,
    card_db: &crate::game::CardDatabase,
    next_timestamp: &mut u32,
) -> Vec<ContinuousEffect> {
    let mut effects = Vec::new();

    for &obj_id in battlefield {
        let inst = match objects.get(&obj_id) {
            Some(i) => i,
            None => continue,
        };
        let def = match card_db.get(inst.card_def_id) {
            Some(d) => d,
            None => continue,
        };

        for sa in &def.static_abilities {
            let generated = sa.to_continuous_effects(obj_id, inst.controller, *next_timestamp);
            *next_timestamp += 1;
            effects.extend(generated);
        }
    }

    effects
}

