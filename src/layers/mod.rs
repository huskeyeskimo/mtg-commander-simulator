        // Verify that layer ordering is correct
        assert!(LayerModification::CopyOf(0).layer() < LayerModification::ChangeController(0).layer());
        assert!(LayerModification::ChangeController(0).layer() < LayerModification::AddType(CardType::Creature).layer());
        assert!(LayerModification::AddType(CardType::Creature).layer() < LayerModification::AddColor(Color::White).layer());
        assert!(LayerModification::AddColor(Color::White).layer() < LayerModification::AddKeyword(KeywordAbility::Flying).layer());
        assert!(LayerModification::AddKeyword(KeywordAbility::Flying).layer() < LayerModification::SetBasePT(0, 0).layer());
        assert!(LayerModification::SetBasePT(0, 0).layer() < LayerModification::SetPT(0, 0).layer());
        assert!(LayerModification::SetPT(0, 0).layer() < LayerModification::ModifyPT(0, 0).layer());
